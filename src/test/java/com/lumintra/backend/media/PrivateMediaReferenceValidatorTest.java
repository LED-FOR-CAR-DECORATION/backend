package com.lumintra.backend.media;

import com.lumintra.backend.media.domain.model.MediaPurpose;
import com.lumintra.backend.media.domain.service.MediaKeyGenerator;
import com.lumintra.backend.media.domain.service.MediaReferenceParser;
import com.lumintra.backend.media.domain.service.PrivateMediaReferenceValidator;
import com.lumintra.backend.media.domain.service.StorageSignedUrlService;
import com.lumintra.backend.shared.exception.media.InvalidMediaUrlException;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class PrivateMediaReferenceValidatorTest {

    private static final String UUID = "123e4567-e89b-12d3-a456-426614174000";
    private static final String CHAT_KEY = "commissions/105/chat/" + UUID + "-photo.png";

    @Mock
    private StorageSignedUrlService storageSignedUrlService;

    private PrivateMediaReferenceValidator validator;

    @BeforeEach
    void setUp() {
        validator = new PrivateMediaReferenceValidator(
                new MediaReferenceParser("https://cdn.lumintra.com", "public-bucket", "private-bucket"),
                new MediaKeyGenerator(),
                storageSignedUrlService
        );
    }

    @Test
    @DisplayName("MED-02 [N]: Uploaded chat key for the same commission is accepted and returned")
    void require_validChatKey() {
        when(storageSignedUrlService.privateObjectExists(CHAT_KEY)).thenReturn(true);

        assertThat(validator.requireOwnedObjectKey(CHAT_KEY, MediaPurpose.COMMISSION_CHAT, 105L)).isEqualTo(CHAT_KEY);
    }

    @Test
    @DisplayName("MED-02 [N]: Legacy CDN URL is normalized to its object key")
    void require_legacyUrlNormalized() {
        when(storageSignedUrlService.privateObjectExists(CHAT_KEY)).thenReturn(true);

        assertThat(validator.requireOwnedObjectKey("https://cdn.lumintra.com/" + CHAT_KEY, MediaPurpose.COMMISSION_CHAT, 105L))
                .isEqualTo(CHAT_KEY);
    }

    @Test
    @DisplayName("MED-02 [N]: Reference image key must sit in the submitting customer's folder")
    void require_referenceScopedToCustomer() {
        String key = "commissions/references/42/" + UUID + "-ref.png";
        when(storageSignedUrlService.privateObjectExists(key)).thenReturn(true);

        assertThat(validator.requireOwnedObjectKey(key, MediaPurpose.COMMISSION_REFERENCE, 42L)).isEqualTo(key);
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(key, MediaPurpose.COMMISSION_REFERENCE, 43L))
                .isInstanceOf(InvalidMediaUrlException.class)
                .hasMessageContaining("customer");
    }

    @Test
    @DisplayName("MED-02 [A]: Media from another commission is rejected without hitting storage")
    void require_otherCommissionRejected() {
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(CHAT_KEY, MediaPurpose.COMMISSION_CHAT, 106L))
                .isInstanceOf(InvalidMediaUrlException.class)
                .hasMessageContaining("commission");
        verify(storageSignedUrlService, never()).privateObjectExists(any());
    }

    @Test
    @DisplayName("MED-02 [A]: Chat upload cannot be reused as a draft")
    void require_wrongPurposeFolderRejected() {
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(CHAT_KEY, MediaPurpose.COMMISSION_DRAFT, 105L))
                .isInstanceOf(InvalidMediaUrlException.class);
    }

    @Test
    @DisplayName("MED-02 [A]: Key not generated by the upload endpoint (no UUID prefix) is rejected")
    void require_nonGeneratedNameRejected() {
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(
                "commissions/105/chat/photo.png", MediaPurpose.COMMISSION_CHAT, 105L))
                .isInstanceOf(InvalidMediaUrlException.class);
    }

    @Test
    @DisplayName("MED-02 [A]: Nested path under the scoped folder is rejected")
    void require_nestedPathRejected() {
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(
                "commissions/105/chat/x/" + UUID + "-photo.png", MediaPurpose.COMMISSION_CHAT, 105L))
                .isInstanceOf(InvalidMediaUrlException.class);
    }

    @Test
    @DisplayName("MED-02 [A]: Foreign URL is rejected")
    void require_foreignUrlRejected() {
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(
                "https://evil.com/" + CHAT_KEY, MediaPurpose.COMMISSION_CHAT, 105L))
                .isInstanceOf(InvalidMediaUrlException.class)
                .hasMessageContaining("not a valid uploaded media object key");
    }

    @Test
    @DisplayName("MED-02 [A]: Key that was never uploaded is rejected")
    void require_notUploadedRejected() {
        when(storageSignedUrlService.privateObjectExists(CHAT_KEY)).thenReturn(false);

        assertThatThrownBy(() -> validator.requireOwnedObjectKey(CHAT_KEY, MediaPurpose.COMMISSION_CHAT, 105L))
                .isInstanceOf(InvalidMediaUrlException.class)
                .hasMessageContaining("has not been uploaded");
    }

    @Test
    @DisplayName("MED-02 [A]: Public purpose or missing scope is a programming error")
    void require_invalidArguments() {
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(CHAT_KEY, MediaPurpose.STORE_PRODUCT, 105L))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> validator.requireOwnedObjectKey(CHAT_KEY, MediaPurpose.COMMISSION_CHAT, null))
                .isInstanceOf(IllegalArgumentException.class);
    }
}
