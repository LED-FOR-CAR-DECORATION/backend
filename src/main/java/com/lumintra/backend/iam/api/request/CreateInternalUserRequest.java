package com.lumintra.backend.iam.api.request;

import com.lumintra.backend.iam.domain.model.InternalUserRole;

import io.swagger.v3.oas.annotations.media.Schema;

import jakarta.validation.constraints.*;

import java.util.Locale;

@Schema(description = "Create an internal account; password is generated by the server")
public record CreateInternalUserRequest(
        @Schema(
                        description = "Unique email, trimmed and lowercase",
                        example = "staff@example.com",
                        requiredMode = Schema.RequiredMode.REQUIRED)
                @NotBlank
                @Email
                @Size(max = 255)
                String email,
        @Schema(
                        description =
                                "Requested internal role; ADMIN and CUSTOMER are not assignable",
                        example = "STAFF",
                        requiredMode = Schema.RequiredMode.REQUIRED)
                @NotNull
                InternalUserRole role,
        @Schema(
                        description = "Optional employee full name, trimmed",
                        example = "Nguyen Van An",
                        requiredMode = Schema.RequiredMode.NOT_REQUIRED)
                @Size(max = 255)
                String name) {
    public CreateInternalUserRequest {
        email = email == null ? null : email.strip().toLowerCase(Locale.ROOT);
        name = name == null || name.isBlank() ? null : name.strip();
    }
}
