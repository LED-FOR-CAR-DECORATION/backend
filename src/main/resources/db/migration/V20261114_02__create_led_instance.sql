-- Reference SQL migration for individual physical LED hardware instances (#173)
CREATE TABLE IF NOT EXISTS led_instance (
    instance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id BIGINT NOT NULL REFERENCES led_model (model_id),
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    mac_address VARCHAR(17) NOT NULL UNIQUE,
    hardware_revision VARCHAR(50),
    current_firmware_id BIGINT,
    device_name VARCHAR(255),
    owner_customer_id BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'IN_STOCK',
    manufactured_at TIMESTAMPTZ,
    bound_at TIMESTAMPTZ,
    warranty_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_led_instance_model_id
    ON led_instance (model_id);

CREATE INDEX IF NOT EXISTS idx_led_instance_status
    ON led_instance (status);

CREATE INDEX IF NOT EXISTS idx_led_instance_owner_customer_id
    ON led_instance (owner_customer_id)
    WHERE owner_customer_id IS NOT NULL;
