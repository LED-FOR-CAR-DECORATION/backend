CREATE TABLE user_account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    account_type VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255), avatar_url VARCHAR(255), status VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE,
    failed_attempts INTEGER NOT NULL DEFAULT 0, lockout_until TIMESTAMP WITH TIME ZONE
);
CREATE TABLE permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_name VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255), created_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(255) NOT NULL UNIQUE, description VARCHAR(255),
    is_system BOOLEAN NOT NULL, created_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL REFERENCES roles(role_id),
    permission_id BIGINT NOT NULL REFERENCES permissions(permission_id),
    PRIMARY KEY (role_id, permission_id)
);
CREATE TABLE customer_profile (
    account_id BIGINT PRIMARY KEY REFERENCES user_account(account_id),
    full_name VARCHAR(255), phone VARCHAR(255), avatar_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE employee_profile (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE REFERENCES user_account(account_id),
    role_id BIGINT NOT NULL REFERENCES roles(role_id),
    full_name VARCHAR(255), phone VARCHAR(255), avatar_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE
);
