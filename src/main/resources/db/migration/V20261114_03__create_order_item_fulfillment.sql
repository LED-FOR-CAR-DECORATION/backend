-- Reference SQL migration for order_item_fulfillment linking physical LED instances to order line items (#93 / #176)
CREATE TABLE IF NOT EXISTS order_item_fulfillment (
    fulfillment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES order_item (order_item_id) ON DELETE CASCADE,
    instance_id BIGINT NOT NULL UNIQUE REFERENCES led_instance (instance_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_item_fulfillment_order_item_id
    ON order_item_fulfillment (order_item_id);
