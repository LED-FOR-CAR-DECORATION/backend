CREATE TABLE IF NOT EXISTS subscription_detail (
    subscription_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE,
    plan_code VARCHAR(100) NOT NULL,
    plan_name VARCHAR(255) NOT NULL,
    is_lifetime BOOLEAN NOT NULL DEFAULT TRUE,
    duration_days INTEGER,
    all_access_characters BOOLEAN NOT NULL DEFAULT FALSE,
    max_commission_revisions INTEGER NOT NULL DEFAULT 0,
    max_mobile_profiles INTEGER NOT NULL DEFAULT 3,
    features JSONB NOT NULL DEFAULT '{}'::jsonb,
    perks_description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT fk_subscription_detail_product
        FOREIGN KEY (product_id) REFERENCES product (product_id) ON DELETE CASCADE,
    CONSTRAINT uq_subscription_detail_plan_code
        UNIQUE (plan_code),
    CONSTRAINT chk_subscription_detail_duration_days
        CHECK (duration_days IS NULL OR duration_days > 0),
    CONSTRAINT chk_subscription_detail_max_commission_revisions
        CHECK (max_commission_revisions >= 0),
    CONSTRAINT chk_subscription_detail_max_mobile_profiles
        CHECK (max_mobile_profiles >= 0)
);

